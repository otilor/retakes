import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { run, UserError } from './proc.js';

// Flows are user journeys recorded in the dock ("search, open a listing") and replayed with
// Playwright on every finished take. They live in the app's repo, in .orch/flows/, as JSON
// plus a generated Playwright test you can run on its own.

export const FLOWS_DIR = path.join('.orch', 'flows');
const PLAYWRIGHT_VERSION = '1.64.1';
const STEP_TIMEOUT = 6000;
const ACTIONS = new Set(['click', 'fill', 'press', 'select', 'check', 'expectText']);

export function flowsDir(appDir) {
  return path.join(appDir, FLOWS_DIR);
}

export function flowId(name) {
  return (
    String(name)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 50) || 'flow'
  );
}

export function loadFlows(appDir) {
  const dir = flowsDir(appDir);
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith('.json')) continue;
    try {
      const flow = validateFlow(JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')));
      out.push({ ...flow, id: file.slice(0, -5) });
    } catch {
      /* a hand-edited file that doesn't parse is skipped, not fatal */
    }
  }
  return out;
}

/** Check a flow from the dock or from disk, and keep only the fields replay understands. */
export function validateFlow(raw) {
  if (!raw || typeof raw !== 'object') throw new UserError('That flow is empty.');
  const name = typeof raw.name === 'string' ? raw.name.trim().slice(0, 80) : '';
  if (!name) throw new UserError('Give the flow a name.');
  const start = typeof raw.start === 'string' && raw.start.startsWith('/') ? raw.start.slice(0, 500) : '/';
  if (!Array.isArray(raw.steps) || !raw.steps.length) throw new UserError('Record at least one step.');
  if (raw.steps.length > 200) throw new UserError('That flow is too long. Keep it under 200 steps.');
  const steps = raw.steps.map((s, i) => {
    if (!s || !ACTIONS.has(s.do)) throw new UserError(`Step ${i + 1} isn't something replay can do.`);
    const target = Array.isArray(s.target) ? s.target.filter((t) => typeof t === 'string' && t).slice(0, 6).map((t) => t.slice(0, 300)) : [];
    if (!target.length) throw new UserError(`Step ${i + 1} has no element to act on.`);
    const step = { do: s.do, target, label: typeof s.label === 'string' ? s.label.slice(0, 120) : '' };
    if (s.do === 'fill' || s.do === 'select') step.value = String(s.value ?? '').slice(0, 2000);
    if (s.do === 'press') step.key = typeof s.key === 'string' && /^[\w+]{1,30}$/.test(s.key) ? s.key : 'Enter';
    if (s.do === 'check') step.checked = !!s.checked;
    if (s.do === 'expectText') {
      step.text = String(s.text ?? '').trim().slice(0, 200);
      if (!step.text) throw new UserError(`Step ${i + 1} checks for text but has none.`);
    }
    return step;
  });
  return { name, start, steps };
}

export function saveFlow(appDir, raw) {
  const flow = validateFlow(raw);
  const dir = flowsDir(appDir);
  fs.mkdirSync(dir, { recursive: true });
  let id = flowId(flow.name);
  if (!raw.id) {
    // A new flow never overwrites another one with the same name.
    for (let n = 2; fs.existsSync(path.join(dir, `${id}.json`)); n++) id = `${flowId(flow.name)}-${n}`;
  } else {
    id = flowId(raw.id);
  }
  fs.writeFileSync(path.join(dir, `${id}.json`), `${JSON.stringify(flow, null, 2)}\n`);
  fs.writeFileSync(path.join(dir, `${id}.spec.mjs`), playwrightSpec(flow));
  return { ...flow, id };
}

export function deleteFlow(appDir, id) {
  const dir = flowsDir(appDir);
  const safe = flowId(id);
  for (const ext of ['.json', '.spec.mjs']) fs.rmSync(path.join(dir, `${safe}${ext}`), { force: true });
}

/** The same flow as a standalone Playwright test, for CI. Uses the first selector of each step. */
export function playwrightSpec(flow) {
  const q = (s) => JSON.stringify(s);
  const lines = flow.steps.map((s) => {
    const el = `page.locator(${q(s.target[0])}).first()`;
    switch (s.do) {
      case 'click':
        return `  await ${el}.click();`;
      case 'fill':
        return `  await ${el}.fill(${q(s.value)});`;
      case 'press':
        return `  await ${el}.press(${q(s.key)});`;
      case 'select':
        return `  await ${el}.selectOption(${q(s.value)});`;
      case 'check':
        return `  await ${el}.setChecked(${s.checked});`;
      case 'expectText':
        return `  await expect(${el}).toContainText(${q(s.text)});`;
      default:
        return '';
    }
  });
  return `// Generated by Orchestrator from ${flowId(flow.name)}.json. Re-recording the flow rewrites this file.
// Run it with: npx playwright test ${FLOWS_DIR.split(path.sep).join('/')}/ --config=<your config> (set baseURL to your dev server)
import { test, expect } from '@playwright/test';

test(${q(flow.name)}, async ({ page }) => {
  await page.goto(${q(flow.start)});
${lines.join('\n')}
});
`;
}

/**
 * Replays flows with Playwright. Uses the app's own Playwright if it has one, then a copy
 * Orchestrator installs once under ~/.orch/runtime. Prefers the Chrome you already have, so
 * most people never download a browser.
 */
export class FlowRunner {
  constructor({ appDir, runtimeDir, log = () => {}, notice = () => {} }) {
    this.appDir = appDir;
    this.runtimeDir = runtimeDir;
    this.log = log;
    this.notice = notice;
    this.browser = null;
    this.starting = null;
    this.queue = Promise.resolve();
  }

  /** Run one replay at a time, in order. */
  enqueue(job) {
    const p = this.queue.then(job, job);
    this.queue = p.catch(() => {});
    return p;
  }

  /** The app's own Playwright if it has one, else the copy under ~/.orch/runtime (installed once). */
  async playwright({ runtimeOnly = false } = {}) {
    const found = (!runtimeOnly && loadFrom(this.appDir)) || loadFrom(this.runtimeDir);
    if (found) return found;
    this.notice('info', 'Setting up flow replays. This happens once.');
    this.log(`flows: installing playwright-core into ${this.runtimeDir}`);
    fs.mkdirSync(this.runtimeDir, { recursive: true });
    if (!fs.existsSync(path.join(this.runtimeDir, 'package.json'))) {
      fs.writeFileSync(path.join(this.runtimeDir, 'package.json'), '{ "name": "orch-runtime", "private": true }\n');
    }
    await run('npm', ['install', '--no-audit', '--no-fund', '--save-exact', `playwright-core@${PLAYWRIGHT_VERSION}`], {
      cwd: this.runtimeDir,
      timeout: 300_000,
    });
    const mod = loadFrom(this.runtimeDir);
    if (!mod) throw new Error("Couldn't load Playwright after installing it.");
    return mod;
  }

  async launch() {
    if (this.browser && this.browser.isConnected()) return this.browser;
    if (this.starting) return this.starting;
    this.starting = (async () => {
      const pw = await this.playwright();
      // Playwright's own browser if it's installed, then the Chrome or Edge you already have.
      for (const opts of [{}, { channel: 'chrome' }, { channel: 'msedge' }]) {
        try {
          return await pw.mod.chromium.launch({ headless: true, ...opts });
        } catch {
          /* try the next browser */
        }
      }
      // No browser at all: download Playwright's Chromium once (about 150 MB), for the runtime copy.
      const rt = await this.playwright({ runtimeOnly: true });
      this.notice('info', 'Downloading a browser for flow replays (about 150 MB, once).');
      this.log('flows: downloading Chromium for replays');
      const cli = createRequire(path.join(this.runtimeDir, 'package.json')).resolve(`${rt.name}/cli.js`);
      await run(process.execPath, [cli, 'install', 'chromium'], { cwd: this.runtimeDir, timeout: 900_000 });
      return rt.mod.chromium.launch({ headless: true });
    })();
    try {
      this.browser = await this.starting;
      return this.browser;
    } finally {
      this.starting = null;
    }
  }

  /** Replay one flow against a dev server. Never throws: problems come back in the result. */
  async replay(flow, baseUrl, { screenshot } = {}) {
    const started = Date.now();
    const problems = [];
    let context = null;
    let page = null;
    let stepIndex = -1;
    try {
      const browser = await this.launch();
      context = await browser.newContext({ viewport: { width: 1280, height: 800 }, baseURL: baseUrl });
      page = await context.newPage();
      const origin = new URL(baseUrl).origin;
      page.on('pageerror', (e) => problems.push(`Page error: ${e.message}`));
      page.on('console', (m) => {
        if (m.type() === 'error' && !/Download the React DevTools|\[HMR\]|\[vite\]/i.test(m.text())) problems.push(`Console error: ${m.text()}`);
      });
      page.on('response', (r) => {
        if (r.status() >= 500 && r.url().startsWith(origin)) problems.push(`Request failed: ${r.status()} ${r.request().method()} ${new URL(r.url()).pathname}`);
      });
      await page.goto(flow.start, { waitUntil: 'load', timeout: 60_000 });
      for (stepIndex = 0; stepIndex < flow.steps.length; stepIndex++) {
        await runStep(page, flow.steps[stepIndex]);
      }
      stepIndex = -1;
      await page.waitForTimeout(300);
      const unique = [...new Set(problems)];
      if (screenshot) await page.screenshot({ path: screenshot }).catch(() => {});
      return {
        ok: unique.length === 0,
        failedStep: null,
        error: unique.length ? unique[0] : null,
        problems: unique.slice(0, 10),
        ms: Date.now() - started,
      };
    } catch (err) {
      if (page && screenshot) await page.screenshot({ path: screenshot }).catch(() => {});
      const step = stepIndex >= 0 ? flow.steps[stepIndex] : null;
      return {
        ok: false,
        failedStep: stepIndex >= 0 ? stepIndex + 1 : null,
        error: step ? `Step ${stepIndex + 1} (${describeStep(step)}): ${firstLine(err.message)}` : firstLine(err.message),
        problems: [...new Set(problems)].slice(0, 10),
        ms: Date.now() - started,
      };
    } finally {
      if (context) await context.close().catch(() => {});
    }
  }

  async close() {
    const b = this.browser;
    this.browser = null;
    if (b) await b.close().catch(() => {});
  }
}

function loadFrom(base) {
  const req = createRequire(path.join(base, 'package.json'));
  for (const name of ['playwright-core', 'playwright', '@playwright/test']) {
    try {
      const mod = req(name);
      if (mod && mod.chromium) return { mod, name };
    } catch {
      /* not installed there */
    }
  }
  return null;
}

async function locate(page, step) {
  const deadline = Date.now() + STEP_TIMEOUT;
  for (;;) {
    for (const sel of step.target) {
      const loc = page.locator(sel);
      const n = await loc.count().catch(() => 0);
      if (n > 0) return loc.first();
    }
    if (Date.now() > deadline) throw new Error(`Couldn't find ${step.label || step.target[0]}`);
    await page.waitForTimeout(150);
  }
}

async function runStep(page, step) {
  const el = await locate(page, step);
  const opts = { timeout: STEP_TIMEOUT };
  switch (step.do) {
    case 'click':
      await el.click(opts);
      break;
    case 'fill':
      await el.fill(step.value, opts);
      break;
    case 'press':
      await el.press(step.key, opts);
      break;
    case 'select':
      await el.selectOption(step.value, opts);
      break;
    case 'check':
      await el.setChecked(step.checked, opts);
      break;
    case 'expectText': {
      const deadline = Date.now() + STEP_TIMEOUT;
      let text = '';
      while (Date.now() < deadline) {
        text = ((await el.innerText().catch(() => '')) || '').replace(/\s+/g, ' ');
        if (text.toLowerCase().includes(step.text.toLowerCase())) return;
        await page.waitForTimeout(150);
      }
      throw new Error(`Expected it to say "${step.text}", but it says "${text.slice(0, 80)}"`);
    }
    default:
      break;
  }
  await page.waitForLoadState('domcontentloaded').catch(() => {});
}

export function describeStep(s) {
  const what = s.label || s.target[0];
  switch (s.do) {
    case 'click':
      return `click ${what}`;
    case 'fill':
      return `type "${clip(s.value, 30)}" into ${what}`;
    case 'press':
      return `press ${s.key} in ${what}`;
    case 'select':
      return `choose "${clip(s.value, 30)}" in ${what}`;
    case 'check':
      return `${s.checked ? 'check' : 'uncheck'} ${what}`;
    case 'expectText':
      return `check ${what} says "${clip(s.text, 40)}"`;
    default:
      return what;
  }
}

function firstLine(s) {
  return String(s || '').split('\n').find((l) => l.trim()) || '';
}

function clip(s, n) {
  s = String(s || '');
  return s.length > n ? `${s.slice(0, n - 1)}…` : s;
}
